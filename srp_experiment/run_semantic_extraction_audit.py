from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from srp_experiment.analysis.semantic_extraction_audit import (
    load_semantic_extraction_records,
    summarize_semantic_extraction_audit,
    write_semantic_extraction_audit_outputs,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run the SRP semantic extraction audit.")
    parser.add_argument(
        "--records-jsonl",
        type=Path,
        default=PROJECT_ROOT / "srp_experiment" / "tmp" / "graph_representation_ablation" / "graph_representation_ablation_records.jsonl",
        help="Input records JSONL generated by the graph representation ablation.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=PROJECT_ROOT / "srp_experiment" / "tmp" / "semantic_extraction_audit",
        help="Directory for JSONL, CSV, markdown, and summary outputs.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    records = load_semantic_extraction_records(args.records_jsonl)
    summary = summarize_semantic_extraction_audit(records)
    outputs = write_semantic_extraction_audit_outputs(records, args.output_dir)
    summary["outputs"] = {key: str(value) for key, value in outputs.items()}
    print(json.dumps(summary, ensure_ascii=False, indent=2, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
